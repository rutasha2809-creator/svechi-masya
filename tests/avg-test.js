/* ============================================================
   avg-test.js — средневзвешенная себестоимость

   Проверяет схему бухгалтера из файла
   «стоимость списания товаров_упрощенный.xlsx»:

     средняя за месяц = (сумма остатка на начало + сумма закупок месяца)
                      / (кол-во на начало        + закупленное количество)

   Контрольный пример бухгалтера:
     остаток на начало 10 ед / 150 ₽, приход 20 ед / 350 ₽, расход 6 ед
     → средняя 16,67 ₽, списано 100,02 ₽, остаток 24 ед / 399,98 ₽

   Запуск:  node tests/avg-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

const МЕС1 = Date.UTC(2026, 3, 15, 12); // апрель 2026
const МЕС2 = Date.UTC(2026, 4, 15, 12); // май 2026

const материал = {
  id: 'test::воск', g: 'wax', n: 'Воск для теста', u: 'г', bu: 'г',
  p: 15, s: 0, min: 0, x: {},
  lots: [
    // апрель: купили 10 ед за 150 ₽ — это и станет остатком на начало мая
    { id: 'L1', q: 10, q0: 10, p: 15, d: МЕС1, bq: 10, bu: 'г', sum: 150 },
    // май: купили 20 ед за 350 ₽
    { id: 'L2', q: 20, q0: 20, p: 17.5, d: МЕС2, bq: 20, bu: 'г', sum: 350 },
  ],
};
S.materials.push(материал);

// в мае списали 6 ед
S.log.push({ t: 'make', d: МЕС2, id: 'r1', n: 'изделие', q: 1, use: [{ id: материал.id, n: материал.n, q: 6 }] });

const ведомость = app.ledger(материал);
const апрель = ведомость.find(x => x.ym === '2026-04');
const май = ведомость.find(x => x.ym === '2026-05');

T.head('Апрель: только закупка, расхода нет');
T.check(!!апрель, 'строка за апрель есть');
T.near(апрель.iq, 10, 0.0001, 'закуплено, ед');
T.near(апрель.is, 150, 0.005, 'закуплено, ₽');
T.near(апрель.wq, 0, 0.0001, 'списано, ед');
T.near(апрель.cq, 10, 0.0001, 'остаток на конец, ед');
T.near(апрель.cs, 150, 0.005, 'остаток на конец, ₽');

T.head('Май: контрольный пример бухгалтера');
T.check(!!май, 'строка за май есть');
T.near(май.oq, 10, 0.0001, 'остаток на начало, ед');
T.near(май.os, 150, 0.005, 'остаток на начало, ₽');
T.near(май.iq, 20, 0.0001, 'приход, ед');
T.near(май.is, 350, 0.005, 'приход, ₽');
T.near(май.avg, 16.67, 0.005, 'средняя себестоимость, ₽');
T.near(май.wSum, 100.02, 0.005, 'списано, ₽');
T.near(май.cq, 24, 0.0001, 'остаток на конец, ед');
T.near(май.cs, 399.98, 0.005, 'остаток на конец, ₽');

T.head('Остаток переходит на следующий месяц');
const июнь = ведомость.find(x => x.ym === '2026-06');
T.check(!!июнь, 'строка за июнь есть (месяцы идут подряд, без пропусков)');
T.near(июнь.oq, 24, 0.0001, 'на начало июня, ед');
T.near(июнь.os, 399.98, 0.005, 'на начало июня, ₽');

T.head('Списали больше, чем было');
const мало = {
  id: 'test::мало', g: 'wax', n: 'Материал с перерасходом', u: 'г', bu: 'г', p: 10, s: 0, min: 0, x: {},
  lots: [{ id: 'L3', q: 0, q0: 5, p: 10, d: МЕС2, bq: 5, bu: 'г', sum: 50 }],
};
S.materials.push(мало);
S.log.push({ t: 'make', d: МЕС2, id: 'r2', n: 'изделие', q: 1, use: [{ id: мало.id, n: мало.n, q: 8 }] });
const строка = app.ledgerAt(мало, '2026-05');
T.near(строка.wq, 5, 0.0001, 'списано не больше, чем было, ед');
T.near(строка.over, 3, 0.0001, 'перерасход показан отдельно, ед');
T.near(строка.cq, 0, 0.0001, 'остаток не ушёл в минус');

T.head('Две себестоимости рядом');
S.recipes.push({
  id: 'r1', n: 'Тестовое изделие', c: 'тест', p: {}, l: [
    { r: 1, lb: 'материал', g: 'wax', m: материал.id, q: { type: 'const', value: 10 }, cf: 'mul' },
  ], mk: [], en: [], tl: [],
});
const рец = app.REC('r1');
const обе = app.costs(рец);
T.near(обе.lot, 150, 0.01, 'по цене партии, ₽ (10 г × 15 ₽ из первой партии)');
T.check(обе.avg > 0 && Math.abs(обе.avg - обе.lot) > 0.01,
  'по средневзвешенной цифра другая: ' + обе.avg.toFixed(2) + ' ₽ против ' + обе.lot.toFixed(2) + ' ₽');

T.head('Переключатель «Себестоимость считать»');
S.settings.base = 'lot';
T.near(app.calc(рец).cost, обе.lot, 0.01, 'при «по партии» берётся цена партии');
S.settings.base = 'avg';
T.near(app.calc(рец).cost, обе.avg, 0.01, 'при «по средневзвешенной» берётся средняя');
S.settings.base = 'lot';

T.done('средневзвешенная');
