/* ============================================================
   pack-test.js — упаковки в изделии больше нет

   Что проверяем:
   1. У изделия без строк упаковки блок «Упаковка» в карточке
      НЕ рисуется вовсе — даже если в составе остались пустые
      слоты упаковки. Раньше блок висел пустым, и убрать его
      из интерфейса было нечем.
   2. У старого изделия, где строка упаковки осталась заполненной,
      блок виден и в нём есть кнопка «Удалить все строки упаковки».
   3. delPackLines() действительно вычищает строки из S.recipes
      (не только из черновика D), после чего блок исчезает.
   ============================================================ */
const T = require('./harness.js');
const app = T.loadApp();
const S = T.withSeed(app);

const ЗАГОЛОВОК = /<h3 class="sm">Упаковка<\/h3>/;
const packLines = r => (r.l || []).filter(x => app.PACK_G.has(x.g));

function карточка(rec) {
  app.Did = rec.id;
  app.D = JSON.parse(JSON.stringify(rec));
  return app.recipeView();
}

T.head('Изделие без упаковки');
const чистое = S.recipes.find(r => !packLines(r).some(x => x.m));
if (!чистое) T.fail('в примере из Excel не нашлось изделия без заполненной упаковки');
const h1 = карточка(чистое);
T.check(!ЗАГОЛОВОК.test(h1), 'блока «Упаковка» в карточке нет: ' + чистое.n);
T.check(/<h3 class="sm">Материалы<\/h3>/.test(h1), 'блок «Материалы» на месте');

T.head('Старое изделие со строкой упаковки');
const старое = S.recipes.find(r => packLines(r).some(x => x.m));
if (!старое) T.fail('в примере из Excel не нашлось изделия со строкой упаковки');
const h2 = карточка(старое);
T.check(ЗАГОЛОВОК.test(h2), 'блок «Упаковка» виден: ' + старое.n);
T.check(/delPackLines\(\)/.test(h2), 'есть кнопка «Удалить все строки упаковки»');

T.head('Удаление строк упаковки');
app.Did = старое.id;
app.D = JSON.parse(JSON.stringify(старое));
app.delPackLines();
const после = app.S.recipes.find(x => x.id === старое.id);
T.check(packLines(после).length === 0, 'строки упаковки убраны из самого изделия, а не только из черновика');
T.check(!ЗАГОЛОВОК.test(app.recipeView()), 'блок «Упаковка» после удаления не рисуется');

T.head('Добавить упаковку в изделие нельзя');
const src = require('fs').readFileSync(T.FILE, 'utf8');
T.check(/const addable=k==='mat'/.test(src), 'кнопка «добавить» осталась только у материалов');
T.check(/groupKeys\(\)\.filter\(g=>!PACK_G\.has\(g\)\)/.test(src), 'разделы упаковки не показываются в списке выбора материала');

T.done('упаковка в изделии');
