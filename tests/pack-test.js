/* ============================================================
   pack-test.js — упаковка в изделии

   Решение владельца от 30.08.2026: упаковку снова заводят в
   изделии. Её стоимость входит в себестоимость как обычный
   материал, НО проценты общепроизводственных и общехозяйственных
   на неё не начисляются: стоимость упаковки уже сидит в самих
   этих расходах, начислять сверху — задвоение.

   Упаковку по-прежнему можно завести и в заказе. Если одна и та
   же позиция стоит в обоих местах, перед списанием приложение
   предупреждает — иначе со склада уйдёт дважды.
   ============================================================ */
const T = require('./harness.js');
const app = T.loadApp();
const S = T.withEmpty(app);

S.settings.opr = 10; S.settings.ohr = 2;

const воск = { id: 'm::wax', g: 'wax', n: 'Воск', u: 'г', bu: 'кг', p: 1, s: 1000, min: 0, x: {}, lots: [] };
const коробка = { id: 'm::box', g: 'box', n: 'Коробка', u: 'шт', bu: 'шт', p: 50, s: 100, min: 0, x: {}, lots: [] };
S.materials.push(воск, коробка);

const изделие = {
  id: 'r1', n: 'Свеча', c: 'тест', p: {}, mk: [], en: [], tl: [],
  l: [
    { r: 1, lb: 'материал', g: 'wax', m: воск.id, q: { type: 'const', value: 100 }, cf: 'mul' },
    { r: 2, lb: 'упаковка', g: 'box', m: коробка.id, q: { type: 'const', value: 1 }, cf: 'mul' },
  ],
};
S.recipes.push(изделие);

T.head('Упаковка входит в себестоимость');
const c = app.calc(изделие);
/* Воск 100 г × 1 ₽ = 100. Коробка 1 × 50 ₽ = 50.
   Проценты берутся только с воска: 100 × 10 % = 10, 100 × 2 % = 2.
   Итого 100 + 50 + 10 + 2 = 162. */
T.near(c.cost, 162, 0.01, 'себестоимость с коробкой, ₽');
T.near(c.прямые, 100, 0.01, 'база процентов — без упаковки, ₽');
T.near(c.упаковка, 50, 0.01, 'упаковка посчитана отдельно, ₽');

T.head('Проценты на упаковку не начисляются');
/* Сторож против возврата задвоения: если упаковку вернут в базу процентов,
   себестоимость станет 100 + 50 + 15 + 3 = 168, и здесь будет ошибка. */
const опр = c.det.find(x => x.k === 'k' && x.acc === 'opr');
const охр = c.det.find(x => x.k === 'k' && x.acc === 'ohr');
T.near(опр.c, 10, 0.01, 'общепроизводственные, ₽ (10 % от 100, а не от 150)');
T.near(охр.c, 2, 0.01, 'общехозяйственные, ₽ (2 % от 100, а не от 150)');

T.head('Без упаковки всё как было');
const без = { ...изделие, id: 'r2', l: [изделие.l[0]] };
S.recipes.push(без);
T.near(app.calc(без).cost, 112, 0.01, 'изделие без упаковки, ₽ (100 + 10 + 2)');

T.head('Упаковка списывается со склада вместе с изделием');
app.makeBatch(app.REC('r1'), 2);
T.near(app.stockOf(коробка), 98, 0.0001, 'две коробки ушли со склада');
T.near(app.stockOf(воск), 800, 0.0001, 'воска ушло 200 г');

T.head('В заказе нельзя выбрать то, что уже есть в изделии');
/* Главная защита от задвоения: коробка, входящая в состав изделия заказа,
   в списке «Упаковка заказа» помечена и не выбирается. */
const заказ0 = { id: 'o0', d: Date.now(), n: 'Заказ', tax: 'none',
  items: [{ rid: 'r1', n: 'Свеча', q: 1, price: 500 }], pack: [] };
S.orders = [заказ0];
app.ordId = 'o0';
app.ordAddPack();
const список = app.pickRender('Упаковка заказа');
T.check(/уже в изделии/.test(список), 'коробка помечена «уже в изделии»');
T.check(!(new RegExp('pickToggle\\(&quot;' + коробка.id + '|pickToggle\\(\'' + коробка.id).test(список)),
  'нажать на неё нельзя');
app.pickToggle(коробка.id);
T.check(app.pickState.sel.length === 0, 'галочка не ставится даже по прямому вызову');
app.pickAllShown([коробка.id]);
T.check(app.pickState.sel.length === 0, '«отметить все показанные» её тоже не берёт');
app.pickDone();
T.check((app.ORD('o0').pack || []).length === 0, 'в упаковку заказа ничего не попало');

T.head('Двойная упаковка — изделие и заказ — предупреждает');
const заказ = { id: 'o1', d: Date.now(), n: 'Заказ', tax: 'none',
  items: [{ rid: 'r1', n: 'Свеча', q: 1, price: 500 }],
  pack: [{ mid: коробка.id, n: 'Коробка', u: 'шт', q: 1 }] };
S.orders = [заказ];
const двойные = app.packDouble(заказ);
T.check(двойные.length === 1 && двойные[0].includes('Коробка'), 'приложение видит коробку и в изделии, и в заказе');
const чистый = { ...заказ, pack: [] };
T.check(app.packDouble(чистый).length === 0, 'без упаковки в заказе предупреждать не о чем');

T.done('упаковка в изделии');
