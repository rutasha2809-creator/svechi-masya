/* ============================================================
   acc-test.js — общепроизводственные и общехозяйственные в ведомости

   Две накопительные позиции. Пополняются закупками из разделов справочника,
   отмеченных соответственно; списываются процентами, которые начислены на
   изделия при выпуске. Разница копится: остаток на конец месяца переходит
   на начало следующего, как у материалов.

   Плюс итоговые строки ведомости.

   Запуск:  node tests/acc-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

const МЕС1 = Date.UTC(2026, 3, 15, 12); // апрель
const МЕС2 = Date.UTC(2026, 4, 15, 12); // май

const мат = (id, g, n, цена) => {
  const m = { id, g, n, u: 'шт', bu: 'шт', p: цена, s: 0, min: 0, x: {}, lots: [] };
  S.materials.push(m); return m;
};
const воск = мат('m::wax', 'wax', 'Воск', 1);
const перчатки = мат('m::gl', 'gloves', 'Перчатки', 5);
const реклама = мат('m::pr', 'promo', 'Реклама в ВК', 100);
воск.u = 'г'; воск.bu = 'г';
воск.lots = [{ id: 'L0', q: 100000, q0: 100000, p: 1, d: МЕС1, sum: 100000 }];

const изделие = {
  id: 'r1', n: 'Свеча', c: 'тест', p: {}, en: [], tl: [], ex: 0,
  l: [{ r: 1, lb: 'воск', g: 'wax', m: воск.id, q: { type: 'const', value: 100 }, cf: 'mul' }],
  mk: [],
};
S.recipes.push(изделие);

T.head('Разделы справочника помечаются');
T.check(app.groupAcc('gloves') === null, 'по умолчанию раздел ни к чему не отнесён');
app.setGroupAcc('gloves', 'opr');
app.setGroupAcc('promo', 'ohr');
T.check(app.groupAcc('gloves') === 'opr', 'перчатки — общепроизводственные');
T.check(app.groupAcc('promo') === 'ohr', 'реклама — общехозяйственные');
app.setGroupAcc('gloves', '');
T.check(app.groupAcc('gloves') === null, 'отметку можно снять');
app.setGroupAcc('gloves', 'opr');

T.head('Косвенные начисляются по общим ставкам');
/* Своих процентных строк у изделия больше нет: ОПР и ОХР приходят из настроек
   и начисляются от суммы прямых затрат — одной строкой каждая. */
const расчёт = app.calc(изделие);
T.near(расчёт.прямые, 100, 0.01, 'прямые затраты, ₽ (воск 100 г × 1 ₽)');
T.near(расчёт.det.find(x => x.acc === 'opr').c, 10, 0.01, 'общепроизводственные 10 %, ₽');
T.near(расчёт.det.find(x => x.acc === 'ohr').c, 2, 0.01, 'общехозяйственные 2 %, ₽');
T.check(расчёт.det.filter(x => x.k === 'k').length === 2, 'в расчёте ровно две строки косвенных');

T.head('Выпуск записывает начисления в журнал');
app.makeBatch(app.REC('r1'), 5);
const выпуск = S.log.find(e => e.t === 'make');
T.check(!!выпуск.acc, 'разбивка записана');
// себестоимость: воск 100 ₽ → ОПР 10 ₽, ОХР 2 ₽ на изделие, × 5 штук
T.near(выпуск.acc.opr, 50, 0.01, 'начислено общепроизводственных, ₽');
T.near(выпуск.acc.ohr, 10, 0.01, 'начислено общехозяйственных, ₽');

T.head('Пополнение приходит из закупок');
перчатки.lots = [{ id: 'L1', q: 100, q0: 100, p: 5, d: Date.now(), sum: 500 }];
реклама.lots = [{ id: 'L2', q: 1, q0: 1, p: 900, d: Date.now(), sum: 900 }];
const ym = app.curYM();
const opr = app.accAt('opr', ym), ohr = app.accAt('ohr', ym);
T.near(opr.in, 500, 0.01, 'общепроизводственные пополнены закупкой перчаток, ₽');
T.near(ohr.in, 900, 0.01, 'общехозяйственные пополнены закупкой рекламы, ₽');

T.head('Списание уходит из этих же строк');
T.near(opr.out, 50, 0.01, 'списано общепроизводственных, ₽');
T.near(ohr.out, 10, 0.01, 'списано общехозяйственных, ₽');
T.near(opr.c, 450, 0.01, 'остаток общепроизводственных на конец, ₽ (500 − 50)');
T.near(ohr.c, 890, 0.01, 'остаток общехозяйственных на конец, ₽ (900 − 10)');

T.head('Закупки из отмеченных разделов не идут в изделия');
T.check(app.groupAcc(перчатки.g) === 'opr', 'раздел перчаток отмечен');
T.check(!изделие.l.some(l => l.m === перчатки.id), 'в составе изделия перчаток нет');

T.head('Месяцы не смешиваются');
перчатки.lots.push({ id: 'L3', q: 50, q0: 50, p: 6, d: МЕС2, sum: 300 });
const май = app.accAt('opr', '2026-05');
T.near(май.in, 300, 0.01, 'майская закупка попала в май, ₽');
T.near(app.accAt('opr', ym).in, 500, 0.01, 'в текущем месяце по-прежнему 500 ₽');

T.head('Остаток переходит на следующий месяц');
/* В мае пополнили на 300 ₽ и ничего не списали — вся сумма должна оказаться
   на начало июня и дальше копиться до текущего месяца. */
T.near(май.out, 0, 0.01, 'в мае списаний не было, ₽');
T.near(май.c, 300, 0.01, 'остаток на конец мая, ₽');
const июнь = app.accAt('opr', '2026-06');
T.check(!!июнь, 'строка за июнь есть — месяцы идут подряд, без пропусков');
T.near(июнь.o, 300, 0.01, 'на начало июня, ₽');
T.near(июнь.in, 0, 0.01, 'в июне пополнений не было, ₽');
T.near(июнь.c, 300, 0.01, 'остаток не изменился, ₽');
T.near(app.accAt('opr', ym).o, 300, 0.01, 'к текущему месяцу пришло 300 ₽ с прошлых');
T.near(app.accAt('opr', ym).c, 300 + 500 - 50, 0.01, 'остаток на конец текущего месяца, ₽');

T.head('Выпуски без разбивки видны отдельно');
S.log.push({ t: 'make', d: Date.now(), id: 'r1', n: 'Свеча', q: 1, cost: 100, use: [] });
T.check(app.accNoBreak(ym) === 1, 'приложение считает записи без разбивки');
T.check(app.accHtml(ym).includes('Выпусков без разбивки'), 'и говорит о них в ведомости');
S.log = S.log.filter(e => e.acc || e.t !== 'make');

T.head('Ведомость: итоговые строки');
app.avgYM = ym;
const h = app.avgView();
T.check(h.includes('ИТОГО по материалам'), 'итоговая строка под таблицей материалов');
T.check(h.includes('Расходы общей суммой'), 'блок с общепроизводственными и общехозяйственными');
T.check(h.includes('На начало') && h.includes('Пополнение') && h.includes('Списание') && h.includes('На конец'),
  'у обеих статей видно движение целиком');
T.check(h.includes('ИТОГО за месяц'), 'общая сводка внизу');
T.check(h.includes('Ушло в производство за месяц'), 'в сводке есть общая сумма');

T.head('Если разделы не отмечены — ведомость предупреждает');
const было = JSON.parse(JSON.stringify(app.accGroups()));
S.accGroups = {};
T.check(app.accHtml(ym).includes('Ни один раздел справочника не отмечен'), 'подсказка появилась');
S.accGroups = было;
T.check(!app.accHtml(ym).includes('Ни один раздел справочника не отмечен'), 'и пропала, когда разделы отмечены');

T.head('Экраны строятся');
for (const [имя, fn] of [
  ['Ведомость', () => app.avgView()],
  ['Разделы справочника', () => app.groupsView()],
  ['Расходы общей суммой', () => app.accHtml(ym)],
  ['ИТОГО за месяц', () => app.itogoHtml(ym, { os: 0, is: 0, ws: 0, cs: 0 })],
]) {
  try { fn(); T.ok(имя); } catch (e) { T.bad(имя + ' — упал: ' + e.message); }
}

T.done('общепроизводственные и общехозяйственные');
