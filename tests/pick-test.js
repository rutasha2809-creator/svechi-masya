/* ============================================================
   pick-test.js — выбор нескольких позиций галочками

   В изделие почти никогда не добавляют одну строку: нужны воск и отдушка,
   коробка и наполнитель, воскоплав и весы с термометром. Поэтому список
   открывается с галочками — отмечаете сколько нужно и жмёте одну кнопку.

   Работает одинаково для материалов, упаковки и амортизируемых предметов.

   Запуск:  node tests/pick-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

const мат = (id, g, n, u, цена) => {
  const m = { id, g, n, u, bu: u, p: цена, s: 0, min: 0, x: {}, lots: [] };
  S.materials.push(m); return m;
};
const воск = мат('m::wax', 'wax', 'Воск соевый', 'г', 0.5);
const отдушка = мат('m::fr', 'fragrance', 'Отдушка ваниль', 'г', 3);
const коробка = мат('m::box', 'box', 'Коробка крафт', 'шт', 40);
const тишью = мат('m::pack', 'pack', 'Тишью', 'шт', 5);
const воскоплав = мат('m::t1', 'tool', 'Воскоплав', 'исп.', 10);
const весы = мат('m::t2', 'tool', 'Весы', 'исп.', 0.36);
const термометр = мат('m::t3', 'tool', 'Термометр с держателем', 'исп.', 1);

const изделие = {
  id: 'r', n: 'Свеча', c: 'тест', p: {}, l: [], en: [], tl: [], mk: [], ex: 0,
};
S.recipes.push(изделие);
app.D = изделие; app.Did = изделие.id;

T.head('Список открывается с галочками');
app.pickMany('Материалы', 'все', () => {}, { btn: 'Добавить в изделие' });
let html = app.pickRender('Материалы');
T.check(html.includes('class="ckb'), 'галочки на экране есть');
/* Класс .ck уже занят фильтрами на «Складе» — свой квадратик должен быть .ckb,
   иначе те галочки съезжают и текст рядом с ними пропадает. */
T.check(!/class="ck ["']/.test(html), 'чужой класс .ck не используется');
T.check(html.includes('Пока ничего не отмечено'), 'видно, что пока ничего не выбрано');
T.check(html.includes('disabled'), 'кнопка заблокирована, пока ничего не отмечено');

T.head('Отметили — кнопка считает');
app.pickToggle(воск.id);
app.pickToggle(отдушка.id);
html = app.pickRender('Материалы');
T.check(html.includes('Отмечено: 2'), 'счётчик показывает 2');
T.check(html.includes('Добавить в изделие (2)'), 'на кнопке видно количество');
T.check(!html.includes('disabled'), 'кнопка разблокировалась');

T.head('Отметку можно снять');
app.pickToggle(отдушка.id);
T.check(app.pickRender('Материалы').includes('Отмечено: 1'), 'осталась одна');
app.pickToggle(отдушка.id);

T.head('Отметить всё показанное и очистить');
app.pickAllShown([воск.id, отдушка.id, коробка.id]);
T.check(app.pickRender('Материалы').includes('Отмечено: 3'), 'отметились все показанные');
app.pickAllShown([воск.id, отдушка.id, коробка.id]);
T.check(app.pickRender('Материалы').includes('Пока ничего не отмечено'), 'повторное нажатие снимает');
app.pickToggle(воск.id);
app.pickState = app.pickState; // состояние живёт между перерисовками
T.check(app.pickRender('Материалы').includes('Отмечено: 1'), 'отметка пережила перерисовку');

T.head('Материалы добавляются в изделие разом');
app.addLine('mat');
app.pickToggle(воск.id);
app.pickToggle(отдушка.id);
app.pickDone();
T.check(изделие.l.length === 2, 'в составе стало 2 строки (было 0)');
T.check(изделие.l.map(l => l.m).includes(воск.id), 'воск добавлен');
T.check(изделие.l.map(l => l.m).includes(отдушка.id), 'отдушка добавлена');
T.check(изделие.l.every(l => l.lb === 'материал'), 'обе строки помечены как материал');
T.check(изделие.l.every(l => l.q.type === 'const' && l.q.value === 1), 'количество по умолчанию 1 — уточняется потом');
T.check(new Set(изделие.l.map(l => l.r)).size === 2, 'номера строк не совпали');
T.check(изделие.l.find(l => l.m === воск.id).g === 'wax', 'раздел материала подставился сам');

T.head('Два раздельных списка: материалы и упаковка');
/* Упаковку в изделие класть снова можно (решение владельца 30.08.2026),
   но списки не смешиваются: в материалах нет коробок, в упаковке — нет воска. */
app.addLine('mat');
const списокМат = app.pickRender('Материалы изделия');
T.check(списокМат.includes('Воск соевый'), 'воск в списке материалов есть');
T.check(!списокМат.includes('Коробка крафт'), 'коробки в списке материалов нет');
T.check(!списокМат.includes('Тишью'), 'наполнителя там тоже нет');
app.pickDone();

app.addLine('pack');
const списокУп = app.pickRender('Упаковка изделия');
T.check(списокУп.includes('Коробка крафт'), 'коробка в списке упаковки есть');
T.check(!списокУп.includes('Воск соевый'), 'воска в списке упаковки нет');
app.pickToggle(коробка.id);
app.pickDone();
T.check(изделие.l.length === 3, 'коробка добавлена в состав');
const строкаУп = изделие.l.find(l => l.m === коробка.id);
T.check(!!строкаУп && строкаУп.lb === 'упаковка', 'строка помечена как упаковка');

const разметка = app.blockHtml('pack', [], 0, []);
T.check(разметка.includes("addLine('pack')"), 'в блоке упаковки есть своя кнопка «добавить»');
T.check(app.blockHtml('mat', [], 0, []).includes("addLine('mat')"), 'а в блоке материалов — своя');
T.check(!разметка.includes('addOther('), 'чужих кнопок в блок упаковки не заехало');

T.head('Амортизируемые предметы — тем же способом');
app.addOther('t');
app.pickToggle(воскоплав.id);
app.pickToggle(весы.id);
app.pickToggle(термометр.id);
app.pickDone();
T.check(изделие.tl.length === 3, 'добавлено 3 предмета одной кнопкой');
T.check(изделие.tl.map(t => t.m).includes(воскоплав.id), 'воскоплав на месте');
T.check(new Set(изделие.tl.map(t => t.r)).size === 3, 'номера строк не совпали');
T.check(изделие.tl.every(t => t.lb === 'амортизация оборудования'), 'подпись проставлена');

T.head('Амортизация считается по карточкам предметов');
const { det, cost } = app.calc(изделие);
const строкиАморт = det.filter(x => x.k === 't');
T.check(строкиАморт.length === 3, 'в расчёте три строки амортизации');
T.near(строкиАморт.find(x => x.name === 'Воскоплав').c, 10, 0.01, 'воскоплав, ₽');
T.near(строкиАморт.find(x => x.name === 'Весы').c, 0.36, 0.01, 'весы, ₽');
T.near(строкиАморт.find(x => x.name === 'Термометр с держателем').c, 1, 0.01, 'термометр, ₽');
T.near(строкиАморт.reduce((a, x) => a + x.c, 0), 11.36, 0.01, 'амортизация всего, ₽');

T.head('В гипсовом изделии воскоплава просто нет');
const гипс = { id: 'rg', n: 'Гипсовое', c: 'тест', p: {}, l: [], en: [], tl: [], mk: [], ex: 0 };
S.recipes.push(гипс);
app.D = гипс; app.Did = гипс.id;
app.addOther('t');
app.pickToggle(весы.id);
app.pickDone();
const аморт2 = app.calc(гипс).det.filter(x => x.k === 't');
T.check(аморт2.length === 1, 'у гипсового изделия одна строка амортизации');
T.near(аморт2[0].c, 0.36, 0.01, 'только весы, ₽ — воскоплав не приписан');

T.head('Одна позиция — сразу открывается её карточка');
app.D = изделие; app.Did = изделие.id;
const было = изделие.l.length;
app.addLine('mat');
app.pickToggle(воск.id);
app.pickDone();
T.check(изделие.l.length === было + 1, 'добавилась ровно одна строка');

T.head('Ничего не отметили — ничего не добавилось');
const сейчас = изделие.l.length;
app.addLine('mat');
app.pickDone();
T.check(изделие.l.length === сейчас, 'состав не изменился');

T.done('выбор галочками');
