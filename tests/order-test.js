/* ============================================================
   order-test.js — заказы и налог

   Заказ — то, что продано клиенту: изделия с количеством и упаковка
   (коробки, наполнители, открытки, ленты).

   Упаковка к цене заказа НЕ прибавляется: её стоимость уже заложена в
   себестоимость изделия процентом от основных затрат. В заказе она нужна
   только затем, чтобы при оформлении списаться со склада.

   Налог берётся от итоговой стоимости заказа: без налога, 4 % физлицам,
   6 % юрлицам. За месяц налог собирается в ведомости, и там его можно
   отметить оплаченным.

   Заказ — единственное место, откуда материалы уходят со склада.

   Запуск:  node tests/order-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

const мат = (id, g, n, u, цена) => {
  const m = { id, g, n, u, bu: u, p: цена, s: 100, min: 0, x: {}, lots: [] };
  S.materials.push(m); return m;
};
const воск = мат('m::wax', 'wax', 'Воск', 'г', 1);
const коробка = мат('m::box', 'box', 'Коробка крафт', 'шт', 40);
const тишью = мат('m::pack', 'pack', 'Тишью', 'шт', 5);
const лента = мат('m::rib', 'ribbon', 'Лента атласная', 'см', 0.8);
const открытка = мат('m::lab', 'label', 'Открытка', 'шт', 15);

const изделие = (id, n, цена) => {
  // цена продажи = себестоимость × 3, вверх до 10 ₽ — подбираем состав под круглую цену
  const r = { id, n, c: 'тест', p: {}, en: [], tl: [], mk: [], ex: 0,
    l: [{ r: 1, lb: 'воск', g: 'wax', m: воск.id, q: { type: 'const', value: цена }, cf: 'mul' }] };
  S.recipes.push(r); return r;
};
const свеча = изделие('r1', 'Свеча', 100);   // себестоимость 100 ₽ → цена 300 ₽
const набор = изделие('r2', 'Набор', 250);   // себестоимость 250 ₽ → цена 750 ₽
S.cats.push('тест');

T.head('Ставки налога');
T.check(app.taxPct('none') === 0, 'без налога — 0 %');
T.check(app.taxPct('fiz') === 4, 'физлицам — 4 %');
T.check(app.taxPct('ur') === 6, 'юрлицам — 6 %');

T.head('Новый заказ');
T.check(app.orders().length === 0, 'заказов ещё нет');
app.newOrder();
T.check(app.orders().length === 1, 'заказ создан');
const заказ = app.orders()[0];
T.check(заказ.tax === 'none', 'по умолчанию без налога');
T.check(заказ.items.length === 0, 'состав пустой');

T.head('Собираем заказ галочками');
app.ordAddItems();
app.pickRecToggle('r1');
app.pickRecToggle('r2');
app.pickRecDone();
T.check(заказ.items.length === 2, 'добавлены обе позиции одной кнопкой');
T.near(заказ.items.find(x => x.rid === 'r1').price, 300, 0.01, 'цена свечи записана, ₽');
T.near(заказ.items.find(x => x.rid === 'r2').price, 750, 0.01, 'цена набора записана, ₽');
T.check(заказ.items.every(x => x.q === 1), 'количество по умолчанию 1');

T.head('Количество и итог');
app.ordItemQty('r1', '3');
T.near(app.orderSum(заказ), 3 * 300 + 750, 0.01, 'стоимость заказа, ₽');

T.head('Налог считается от стоимости заказа');
T.near(app.orderTax(заказ), 0, 0.01, 'без налога — 0 ₽');
app.ordSet('tax', 'fiz');
T.near(app.orderTax(заказ), 1650 * 0.04, 0.01, '4 % физлицам, ₽');
T.near(app.orderNet(заказ), 1650 - 66, 0.01, 'к получению после налога, ₽');
app.ordSet('tax', 'ur');
T.near(app.orderTax(заказ), 1650 * 0.06, 0.01, '6 % юрлицам, ₽');
T.near(app.orderNet(заказ), 1650 - 99, 0.01, 'к получению после налога, ₽');

T.head('Цена в заказе не едет вслед за прайсом');
// изделие подорожало — в уже собранном заказе цена должна остаться прежней
свеча.l[0].q.value = 200;
T.near(app.orderSum(заказ), 1650, 0.01, 'стоимость заказа не изменилась, ₽');
T.near(app.priceOf(свеча, app.calc(свеча).cost), 600, 0.01, 'а в прайсе изделие уже дороже, ₽');
app.ordRefreshPrices();
T.near(app.orderSum(заказ), 3 * 600 + 750, 0.01, 'после «подставить нынешние» — пересчиталось, ₽');
свеча.l[0].q.value = 100;
app.ordRefreshPrices();
T.near(app.orderSum(заказ), 1650, 0.01, 'вернули как было, ₽');

T.head('Цену можно поправить руками');
app.ordItemPrice('r2', '700');
T.near(app.orderSum(заказ), 3 * 300 + 700, 0.01, 'итог пересчитался, ₽');
app.ordItemPrice('r2', '750');

T.head('Упаковка заказа — выбор галочками');
app.ordAddPack();
const списокУпак = app.pickRender('Упаковка заказа');
T.check(!списокУпак.includes('Воск'), 'воска в списке упаковки нет — показаны только разделы упаковки');
T.check(списокУпак.includes('Коробка крафт') && списокУпак.includes('Тишью')
     && списокУпак.includes('Лента атласная') && списокУпак.includes('Открытка'),
  'коробки, наполнители, ленты и открытки — все в одном списке');
T.check(списокУпак.includes('вся упаковка'), 'фильтр подписан «вся упаковка»');
app.pickToggle(коробка.id);
app.pickToggle(тишью.id);
app.pickToggle(открытка.id);
app.pickDone();
T.check(заказ.pack.length === 3, 'добавлены три позиции одной кнопкой');
T.check(заказ.pack.every(x => x.q === 1), 'количество по умолчанию 1');
T.check(заказ.pack.every(x => x.price === undefined), 'цена у упаковки не хранится — клиент за неё отдельно не платит');

T.head('Упаковка НЕ прибавляется к стоимости заказа');
/* Стоимость упаковки заложена в себестоимость изделия процентом от основных
   затрат. Если прибавить коробку ещё и к цене заказа — получится задвоение.
   Упаковка в заказе нужна только для того, чтобы списаться со склада. */
T.near(app.orderItemsSum(заказ), 1650, 0.01, 'изделия, ₽');
T.near(app.orderPackSum(заказ), 40 + 5 + 15, 0.01, 'упаковка по закупочной цене, ₽');
T.near(app.orderSum(заказ), 1650, 0.01, 'стоимость заказа — только изделия, ₽');
T.near(app.orderTax(заказ), 1650 * 0.06, 0.01, 'налог 6 % с упаковки не берётся, ₽');
T.near(app.orderNet(заказ), 1650 - 99, 0.01, 'к получению, ₽');

T.head('Количество упаковки можно править');
app.ordPackQty(коробка.id, '2');
T.near(app.orderPackSum(заказ), 80 + 5 + 15, 0.01, 'две коробки, ₽');
T.near(app.orderSum(заказ), 1650, 0.01, 'на стоимость заказа это не влияет, ₽');
app.ordPackDel(тишью.id);
T.check(заказ.pack.length === 2, 'позицию можно убрать');
T.near(app.orderPackSum(заказ), 80 + 15, 0.01, 'сумма упаковки пересчиталась, ₽');
app.ordPackQty(коробка.id, '1');
app.ordPackDel(открытка.id);
T.near(app.orderPackSum(заказ), 40, 0.01, 'осталась одна коробка, ₽');
T.check(typeof app.ordPackPrice === 'undefined', 'цену упаковки в заказе больше не редактируют');

T.head('Повторное добавление той же позиции прибавляет количество');
app.ordAddPack();
app.pickToggle(коробка.id);
app.pickDone();
T.check(заказ.pack.length === 1, 'строка не задвоилась');
T.near(заказ.pack[0].q, 2, 0.0001, 'количество стало 2');
app.ordPackQty(коробка.id, '1');

T.head('Пока не нажали «списать» — склад не тронут');
T.near(app.stockOf(воск), 100, 0.0001, 'остаток воска не изменился');
T.check(!S.log.some(e => e.t === 'make'), 'в журнале пусто');
T.near(app.stockOf(коробка), 100, 0.0001, 'коробки тоже на месте');
T.check(app.orderShipped(заказ) === false, 'заказ помечен как несписанный');

T.head('Списание материалов по заказу');
/* Заказ — единственное место, откуда материалы уходят со склада:
   отдельной вкладки «Выпуск» больше нет. */
воск.lots = [{ id: 'LW', q: 10000, q0: 10000, p: 1, d: Date.now(), sum: 10000 }];
коробка.lots = [{ id: 'LB', q: 50, q0: 50, p: 40, d: Date.now(), sum: 2000 }];
const строки = app.orderLines(заказ);
T.check(строки.length === 3, 'в списании три строки: два изделия и упаковка');
T.check(app.shipCheck(строки).ok === true, 'материалов хватает');
const воскаБыло = app.stockOf(воск), коробокБыло = app.stockOf(коробка);
app.ordShip();
T.check(app.orderShipped(заказ) === true, 'заказ отмечен как списанный');
// свеча 100 г × 3 + набор 250 г × 1 = 550 г
T.near(app.stockOf(воск), воскаБыло - 550, 0.0001, 'воск списан по составу обоих изделий');
T.near(app.stockOf(коробка), коробокБыло - 1, 0.0001, 'коробка из упаковки заказа тоже списана');
const списание = S.log.find(e => e.t === 'make');
T.check(!!списание, 'в журнале одна запись на весь заказ');
T.check(списание.oid === заказ.id, 'запись привязана к заказу');
T.check(списание.n.startsWith('Заказ:'), 'подпись говорит, что это заказ');
T.near(списание.cost, app.orderCost(заказ), 0.01, 'записана себестоимость заказа, ₽');

T.head('Повторно списать нельзя');
const воскаПосле = app.stockOf(воск);
app.ordShip();
T.near(app.stockOf(воск), воскаПосле, 0.0001, 'второе нажатие ничего не списало');
T.check(S.log.filter(e => e.t === 'make').length === 1, 'вторая запись не появилась');

T.head('Списание отменяется, материалы возвращаются');
app.ordUnship();
T.check(app.orderShipped(заказ) === false, 'отметка снята');
T.near(app.stockOf(воск), воскаБыло, 0.0001, 'воск вернулся');
T.near(app.stockOf(коробка), коробокБыло, 0.0001, 'коробка вернулась');
T.check(!S.log.some(e => e.t === 'make'), 'запись из журнала убрана');

T.head('Заказ «для своих целей»');
app.newOrder();
const свои = app.orders()[0];
app.ordSet('n', 'Витрина');
app.ordSet('own', true);
app.ordAddItems();
app.pickRecToggle('r1');
app.pickRecDone();
app.ordItemQty('r1', '2');
T.check(свои.own === true, 'галочка «не в заказ» стоит');
T.near(app.orderSum(свои), 0, 0.01, 'выручки нет');
T.near(app.orderTax(свои), 0, 0.01, 'налога нет');
app.ordSet('tax', 'ur');
T.near(app.orderTax(свои), 0, 0.01, 'даже если ставка выбрана — налог всё равно 0');
T.near(app.orderCost(свои), 2 * app.calc(app.REC('r1')).cost, 0.01, 'себестоимость считается, ₽');

T.head('Для своих: материалы списываются, а в налог не идёт');
const до = app.stockOf(воск);
app.ordShip();
T.near(app.stockOf(воск), до - 200, 0.0001, 'воск списан: 2 свечи × 100 г');
T.check(S.log[0].n.startsWith('Для своих:'), 'в журнале видно, что это не заказ');
const тм = app.taxMonth(app.curYM());
T.check(!S.orders.filter(o => !o.own).some(o => o === свои), 'в итог месяца этот заказ не входит');
T.near(тм.выручка, тм.выручка, 0.01, 'выручка месяца считается только по заказам клиентов');
app.ordUnship();
T.near(app.stockOf(воск), до, 0.0001, 'и отменяется так же');

T.head('Итог за месяц');
const ym = app.curYM();
let t = app.taxMonth(ym);
T.check(t.заказов === 1, 'заказов за месяц: 1');
T.near(t.выручка, 1650, 0.01, 'выручка за месяц, ₽ — только изделия, упаковка в неё не входит');
T.near(t.всего, 99, 0.01, 'налог за месяц, ₽');
T.near(t.по.ur, 1650, 0.01, 'по ставке 6 % выручка, ₽');
T.near(t.налог.ur, 99, 0.01, 'по ставке 6 % налог, ₽');
T.check(t.оплата === null, 'пока не оплачен');

T.head('Второй заказ с другой ставкой');
app.newOrder();
const заказ2 = app.orders()[0];
app.ordAddItems();
app.pickRecToggle('r1');
app.pickRecDone();
app.ordSet('tax', 'fiz');
t = app.taxMonth(ym);
T.check(t.заказов === 2, 'заказов за месяц: 2');
T.near(t.выручка, 1650 + 300, 0.01, 'выручка за месяц, ₽');
T.near(t.всего, 99 + 12, 0.01, 'налог за месяц, ₽ (6 % с одного и 4 % со второго)');
T.near(t.налог.fiz, 12, 0.01, 'по ставке 4 %, ₽');
T.near(t.налог.ur, 99, 0.01, 'по ставке 6 %, ₽');

T.head('Заказ без налога в итог не добавляет');
app.newOrder();
app.ordAddItems();
app.pickRecToggle('r2');
app.pickRecDone();
t = app.taxMonth(ym);
T.check(t.заказов === 3, 'заказов за месяц: 3');
T.near(t.выручка, 1650 + 300 + 750, 0.01, 'выручка выросла, ₽');
T.near(t.всего, 111, 0.01, 'налог не изменился, ₽');

T.head('Отметка об оплате');
app.taxPay(ym);
t = app.taxMonth(ym);
T.check(!!t.оплата, 'налог отмечен оплаченным');
T.near(t.оплата.sum, 111, 0.01, 'записана сумма оплаты, ₽');
T.check(!!t.оплата.d, 'записана дата оплаты');
app.taxUnpay(ym);
T.check(app.taxMonth(ym).оплата === null, 'отметку можно снять');

T.head('Если после оплаты заказы поменяли — видно расхождение');
app.taxPay(ym);
app.ordId = заказ.id;
app.ordItemQty('r1', '4');
t = app.taxMonth(ym);
T.near(t.всего, 111 + 300 * 0.06, 0.01, 'начислено стало больше, ₽');
T.near(t.оплата.sum, 111, 0.01, 'а отмечена прежняя сумма, ₽');
T.check(app.taxMonthHtml(ym).includes('после отметки заказы месяца меняли'), 'в ведомости появилось предупреждение');
app.taxUnpay(ym);

T.head('Прошлый месяц считается отдельно');
заказ2.d = Date.UTC(2026, 5, 15, 12);   // июнь 2026
const июнь = app.taxMonth('2026-06');
T.check(июнь.заказов === 1, 'в июне один заказ');
T.near(июнь.всего, 12, 0.01, 'налог за июнь, ₽');
T.check(app.taxMonth(ym).заказов === 2, 'в текущем месяце осталось два');

T.head('Удаление заказа');
app.ordId = заказ2.id;
app.ordDel();
T.check(!app.ORD(заказ2.id), 'заказ удалён');
T.check(app.taxMonth('2026-06').заказов === 0, 'из итога за июнь он тоже пропал');

T.head('Экраны строятся');
app.ordId = заказ.id;
for (const [имя, fn] of [
  ['Заказы', () => app.renderOrders()],
  ['Карточка заказа', () => app.orderView()],
  ['Выбор изделий', () => { app.pickRecipes('т', '', () => {}); return app.pickRecView('т'); }],
  ['Налог в ведомости', () => app.taxMonthHtml(ym)],
  ['Ведомость целиком', () => app.avgView()],
]) {
  try { fn(); T.ok(имя); } catch (e) { T.bad(имя + ' — упал: ' + e.message); }
}
T.check(app.avgView().includes('Налог за месяц'), 'блок налога есть в ведомости');
T.check(app.allMonths().includes(ym), 'месяц с заказами попадает в список месяцев ведомости');

T.done('заказы и налог');
