/* ============================================================
   markup-test.js — косвенные расходы и производные величины

   (в прежнем наборе этот тест назывался sup-test.js)

   Схема расчёта: прямые переменные (материалы поштучно) + прямые постоянные
   (амортизация по позициям) + косвенные. Косвенные — две общие строки,
   одинаковые для всех изделий: общепроизводственные и общехозяйственные,
   процентом от суммы прямых затрат. Своих процентных строк у изделия нет.

   Плюс производные величины: усадка воска, доля отдушки, масса гипса и вода.

   Запуск:  node tests/markup-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

const мат = (id, g, n, u, цена, доп) =>
  Object.assign({ id, g, n, u, bu: u, p: цена, s: 0, min: 0, x: доп || {}, lots: [] }, {});

const A = мат('m::a', 'wax', 'Материал А', 'г', 10);
const B = мат('m::b', 'vessel', 'Материал Б', 'шт', 100);
S.materials.push(A, B);

const изделие = () => ({
  id: 'r', n: 'изделие', c: 'тест', p: {}, en: [], tl: [], mk: [], ex: 0,
  l: [
    { r: 10, lb: 'а', g: 'wax', m: A.id, q: { type: 'const', value: 10 }, cf: 'mul' },     // 100 ₽
    { r: 11, lb: 'б', g: 'vessel', m: B.id, q: { type: 'const', value: 2 }, cf: 'mul' },   // 200 ₽
  ],
});

T.head('Ставки по умолчанию');
T.near(app.accPct('opr'), 10, 0.001, 'общепроизводственные, %');
T.near(app.accPct('ohr'), 2, 0.001, 'общехозяйственные, %');

T.head('Косвенные начисляются от прямых затрат');
const баз = app.calc(изделие());
T.near(баз.прямые, 300, 0.01, 'прямые затраты, ₽');
const опр = баз.det.find(x => x.acc === 'opr'), охр = баз.det.find(x => x.acc === 'ohr');
T.check(!!опр && !!охр, 'в расчёте ровно две строки косвенных');
T.near(опр.c, 30, 0.01, 'общепроизводственные 10 % от 300 ₽');
T.near(охр.c, 6, 0.01, 'общехозяйственные 2 % от 300 ₽');
T.near(баз.cost, 336, 0.01, 'себестоимость, ₽');
/* Обе — от одной базы, а не каскадом друг от друга: 2 % считаются от 300,
   а не от 330. */
T.near(охр.c, 6, 0.01, 'ОХР не считается от суммы с ОПР');

T.head('Амортизация и энергия входят в базу косвенных');
const сАморт = изделие();
сАморт.tl = [{ r: 30, m: null, lb: 'амортизация', v: 100 }];
const c2 = app.calc(сАморт);
T.near(c2.прямые, 400, 0.01, 'прямые с амортизацией, ₽');
T.near(c2.det.find(x => x.acc === 'opr').c, 40, 0.01, 'ОПР 10 % от 400 ₽');

T.head('Ставка берётся из настроек');
S.settings.opr = 15; S.settings.ohr = 0;
const c3 = app.calc(изделие());
T.near(c3.det.find(x => x.acc === 'opr').c, 45, 0.01, 'ОПР 15 % от 300 ₽');
T.near(c3.det.find(x => x.acc === 'ohr').c, 0, 0.01, 'ОХР 0 % — строка есть, но пустая');
T.near(c3.cost, 345, 0.01, 'себестоимость, ₽');

T.head('Своих процентных строк у изделия больше нет');
/* Раньше проценты заводились строками в каждой карточке (r.mk) тремя разными
   способами. Теперь они общие, а старые строки в расчёт не идут — иначе
   у перенесённых из Excel изделий всё задвоилось бы. */
S.settings.opr = 10; S.settings.ohr = 2;
const сСтарой = изделие();
сСтарой.mk = [{ r: 20, lb: 'расходники', pct: 0.5, k: 'all' }];
T.near(app.calc(сСтарой).cost, 336, 0.01, 'старая строка 50 % не изменила себестоимость, ₽');
T.check(!app.calc(сСтарой).det.some(x => x.lb === 'расходники'), 'и в расчёте её не видно');

T.head('Дополнительные расходы');
const доп = изделие(); доп.ex = 55;
T.near(app.calc(доп).cost, 336 + 55, 0.01, 'доп. расходы прибавляются как есть, ₽');
T.near(app.calc(доп).det.find(x => x.acc === 'opr').c, 30, 0.01,
  'но в базу косвенных не входят: ОПР по-прежнему 10 % от 300 ₽');

T.head('Усадка воска и доля отдушки');
/* Округление до ЦЕЛЫХ граммов — мастер отвешивает граммы, дробей на весах нет.
   А вот до десятков округлять нельзя: так делал Excel, и 280 мл давали 270 г
   вместо 266, приписывая изделию лишние граммы. */
const свеча = изделие(); свеча.p = { volWax_A: 200, fragrPct_A: 10 }; свеча.wr = { A: 'ROUND(vol*0.95,0)' };
const d1 = app.calc(свеча).d;
T.near(d1.waxRaw_A, 190, 0.0001, 'сырой воск = 200 × 0,95, г');
T.near(d1.waxNet_A, 173, 0.0001, 'воск = 190 / 110 × 100 = 172,7 → 173 г');
T.near(d1.fragrMass_A, 17, 0.0001, 'отдушка = сырой − воск = 17 г');
T.check(Number.isInteger(d1.waxNet_A) && Number.isInteger(d1.fragrMass_A), 'обе величины целые');
T.near(d1.waxNet_A + d1.fragrMass_A, d1.waxRaw_A, 0.0001, 'воск и отдушка в сумме дают ровно массу — грамм не потерялся');

const без = изделие(); без.p = { volWax_A: 200, fragrPct_A: 0 }; без.wr = { A: 'ROUND(vol*0.95,0)' };
T.near(app.calc(без).d.fragrMass_A, 0, 0.0001, 'без отдушки её масса 0, г');

/* Контрольный пример владельца: 280 мл при 10 % отдушки. */
const контроль = изделие();
контроль.p = { volWax_A: 280, fragrPct_A: 10 };
контроль.wr = { A: '=ROUND($C$4*0.95,-1)' };
const dк = app.calc(контроль).d;
T.near(dк.waxRaw_A, 266, 0.0001, '280 мл × 0,95 = 266 г воска с отдушкой');
T.check(Math.abs(dк.waxRaw_A - 270) > 1, 'до 270 больше не округляется — лишних граммов нет');
T.near(dк.waxNet_A, 242, 0.0001, 'воск 242 г');
T.near(dк.fragrMass_A, 24, 0.0001, 'отдушка 24 г');
T.near(dк.waxNet_A + dк.fragrMass_A, 266, 0.0001, '242 + 24 = 266');

/* Округление не должно терять или добавлять граммы ни на каком объёме. */
for (const v of [175, 238, 250, 300, 333, 512]) {
  контроль.p.volWax_A = v;
  const q = app.calc(контроль).d;
  T.check(Number.isInteger(q.waxNet_A) && Number.isInteger(q.fragrMass_A) && Number.isInteger(q.waxRaw_A),
    v + ' мл — все три величины целые');
  T.near(q.waxNet_A + q.fragrMass_A, q.waxRaw_A, 0.0001, v + ' мл — воск и отдушка дают ровно массу');
}

T.head('Масса гипса и вода');
const гипсМат = мат('m::g', 'gypsum', 'Гипс СКУЛЬПТОР', 'г', 0.05, { coef: 1.65 });
S.materials.push(гипсМат);
const гипс = {
  id: 'rg', n: 'гипсовое', c: 'тест', p: { volGypsum_A: 300 }, en: [], tl: [], mk: [], ex: 0,
  l: [
    { r: 10, lb: 'гипс', g: 'gypsum', m: гипсМат.id, q: { type: 'gypsumMass', volKey: 'volGypsum_A' }, cf: 'mul' },
    { r: 11, lb: 'вода', g: 'gypsum', m: гипсМат.id, q: { type: 'water' }, cf: 'mul' },
  ],
};
S.recipes.push(гипс);
const dг = app.calc(гипс).d;
T.near(dг.gypsum, 495, 0.0001, 'гипс = 300 мл × 1,65, г');
T.near(dг.water, 124, 0.0001, 'вода = 25 % от гипса, г');
const detг = app.calc(гипс).det;
T.near(detг.find(x => x.lb === 'гипс').c, 495 * 0.05, 0.01, 'гипс в деньгах, ₽');
T.near(detг.find(x => x.lb === 'вода').c, 0, 0.0001, 'вода бесплатная — в себестоимость не идёт');

T.head('Коэффициенты гипсовых смесей');
const смеси = { 'СКУЛЬПТОР': 1.65, 'жидкая керамика': 1.75, 'фрипласт': 1.8, 'акрил': 1.95 };
for (const имя in смеси) {
  гипсМат.x.coef = смеси[имя];
  T.near(app.calc(гипс).d.gypsum, 300 * смеси[имя], 0.0001, имя + ' — масса гипса из 300 мл, г');
}

T.head('Процент от массы (правило pct)');
гипсМат.x.coef = 1.65;
const краситель = мат('m::dye', 'dye', 'Пигмент', 'г', 2);
S.materials.push(краситель);
гипс.l.push({ r: 12, lb: 'пигмент', g: 'dye', m: краситель.id, q: { type: 'pct', base: 'gypsum', pct: 0.02 }, cf: 'mul' });
const detп = app.calc(гипс).det.find(x => x.lb === 'пигмент');
T.near(detп.q, 495 * 0.02, 0.0001, 'пигмент = 2 % от массы гипса, г');
T.near(detп.c, 495 * 0.02 * 2, 0.01, 'пигмент в деньгах, ₽');

T.done('косвенные расходы и производные величины');
