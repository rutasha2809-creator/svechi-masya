/* ============================================================
   run-all.js — прогоняет все проверки подряд и печатает итог

   Запуск:  node tests/run-all.js
   или двойной клик по «Проверить приложение.bat» в папке проекта.
   ============================================================ */
const { execFileSync } = require('child_process');
const path = require('path');

const ТЕСТЫ = [
  ['syntax-test.js', 'Целостность файла', 'открывается ли страница вообще'],
  ['test.js', 'Эталон себестоимости', 'не сдвинулись ли цифры по 71 изделию'],
  ['markup-test.js', 'Наценки и массы', 'проценты, усадка воска, отдушка, гипс, вода'],
  ['pick-test.js', 'Выбор галочками', 'материалы, упаковка, амортизируемые предметы'],
  ['order-test.js', 'Заказы и налог', 'ставки 4 % и 6 %, итог за месяц, оплата'],
  ['lot-test.js', 'Партии и склад', 'цена закупки, списание'],
  ['avg-test.js', 'Средневзвешенная', 'пример бухгалтера'],
  ['acc-test.js', 'Расходы общей суммой', 'ОПР и ОХР: пополнение, списание, итого'],
  ['undo-test.js', 'Отмена записи', 'удаление выпуска и закупки, возврат на склад'],
  ['chain-test.js', 'Вся цепочка', 'путь мастера с нуля + все экраны'],
];

console.log('');
console.log('╔══════════════════════════════════════════════════════╗');
console.log('║   ПРОВЕРКА ПРИЛОЖЕНИЯ «СВЕЧИ МАСЯ»                   ║');
console.log('╚══════════════════════════════════════════════════════╝');

const итоги = [];
for (const [файл, имя, что] of ТЕСТЫ) {
  console.log('\n\n──────────────────────────────────────────────────────');
  console.log('  ' + имя + '  —  ' + что);
  console.log('──────────────────────────────────────────────────────');
  try {
    const out = execFileSync(process.execPath, [path.join(__dirname, файл)], { encoding: 'utf8' });
    process.stdout.write(out);
    итоги.push([имя, 'в порядке']);
  } catch (e) {
    process.stdout.write(String(e.stdout || ''));
    process.stderr.write(String(e.stderr || ''));
    итоги.push([имя, e.status === 2 ? 'НЕ ЗАПУСТИЛСЯ' : 'ЕСТЬ ОШИБКИ']);
  }
}

console.log('\n\n╔══════════════════════════════════════════════════════╗');
console.log('║   ИТОГ                                               ║');
console.log('╚══════════════════════════════════════════════════════╝');
let плохо = 0;
for (const [имя, статус] of итоги) {
  if (статус !== 'в порядке') плохо++;
  console.log('  ' + (статус === 'в порядке' ? '✓' : '✗') + '  ' + имя.padEnd(26, ' ') + статус);
}
console.log('');
if (плохо) {
  console.log('  Что-то сломалось. Выкладывать эту версию на сайт НЕ НАДО.');
  console.log('  Пролистайте вверх — рядом со словом ОШИБКА написано, что именно разошлось.');
  process.exit(1);
}
console.log('  Всё сошлось. Версию можно выкладывать: «Обновить сайт.bat».');
process.exit(0);
