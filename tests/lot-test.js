/* ============================================================
   lot-test.js — партии (закупки) и списание со склада

   Главное требование владельца: цена фиксируется в день покупки и
   не усредняется. В расчёт идёт цена конкретной закупки.

   Проверяет:
     — закупку в килограммах при расходе в граммах (пересчёт ×1000);
     — две закупки по разной цене живут рядом, каждая со своей ценой;
     — «партия в работе» — самая старая непустая;
     — если в строке состава выбрана партия, берётся её цена;
     — при выпуске списывается именно выбранная партия.

   Запуск:  node tests/lot-test.js
   ============================================================ */
const T = require('./harness.js');

const app = T.loadApp();
const S = T.withEmpty(app);

/* Косвенные расходы (ОПР и ОХР) в этом тесте выключены: он не про них,
   а про партии и цены закупок. Их собственный тест — markup-test.js. */
S.settings.opr = 0; S.settings.ohr = 0;

const воск = { id: 'wax::тест', g: 'wax', n: 'Воск', u: 'г', bu: 'кг', p: 0, s: 0, min: 0, x: {}, lots: [] };
S.materials.push(воск);

T.head('Первая закупка: 2 кг за 2000 ₽');
app.buyRows = [{ id: воск.id, q: '2', s: '2000', u: 'кг' }];
app.doBuy();
T.near(app.stockOf(воск), 2000, 0.0001, 'на складе, г (килограммы пересчитались в граммы)');
T.near(app.matPrice(воск), 1, 0.0001, 'цена, ₽ за грамм');
T.check(app.sortedLots(воск).length === 1, 'партия одна');

T.head('Вторая закупка: 1 кг за 1500 ₽');
// вторая покупка позже первой — иначе «партия в работе» определится не та
const t0 = app.sortedLots(воск)[0].d;
app.buyRows = [{ id: воск.id, q: '1', s: '1500', u: 'кг' }];
app.doBuy();
const партии = app.sortedLots(воск);
партии[1].d = t0 + 86400000;
T.check(партии.length === 2, 'партий стало две');
T.near(app.stockOf(воск), 3000, 0.0001, 'на складе, г');
T.near(партии[0].p, 1, 0.0001, 'цена первой партии, ₽/г');
T.near(партии[1].p, 1.5, 0.0001, 'цена второй партии, ₽/г');
T.near(app.valueOf_(воск), 2000 * 1 + 1000 * 1.5, 0.01, 'склад в деньгах, ₽');

T.head('Какая партия в работе');
T.check(app.activeLot(воск) === партии[0], 'в работе самая старая непустая — первая');
T.near(app.matPrice(воск), 1, 0.0001, 'без выбора берётся цена партии в работе, ₽/г');
T.near(app.matPrice(воск, партии[1].id), 1.5, 0.0001, 'с выбором берётся цена выбранной, ₽/г');

T.head('Цена партии попадает в себестоимость');
const изделие = {
  id: 'r-test', n: 'Свеча тестовая', c: 'тест', p: {}, mk: [], en: [], tl: [],
  l: [{ r: 1, lb: 'материал', g: 'wax', m: воск.id, q: { type: 'const', value: 100 }, cf: 'mul' }],
};
S.recipes.push(изделие);
T.near(app.calc(изделие, 'lot').cost, 100, 0.01, 'без выбора партии: 100 г × 1 ₽');
изделие.l[0].lot = партии[1].id;
T.near(app.calc(изделие, 'lot').cost, 150, 0.01, 'выбрана вторая партия: 100 г × 1,5 ₽');

T.head('Выбор партии сохраняется сразу');
/* Раньше выбор менял только черновик изделия: уходишь, не нажав «Сохранить», —
   и партия «слетала» обратно на ту, что в работе. */
app.D = JSON.parse(JSON.stringify(изделие)); app.Did = изделие.id;
app.pickLot(1, партии[1].id);
T.check(app.REC('r-test').l[0].lot === партии[1].id, 'выбор попал в базу, а не только в черновик');
const сохранено = JSON.parse(app.localStorage.getItem('masya_cost_v1'));
T.check(сохранено.recipes[0].l[0].lot === партии[1].id, 'и записался на диск');
app.pickLot(1, '');
T.check(!app.REC('r-test').l[0].lot, 'сброс на «ту, что в работе» тоже сохраняется');
app.pickLot(1, партии[1].id);
/* И сам выпадающий список должен звать pickLot, а не менять черновик напрямую. */
app.toggleLot(1);
const списокПартий = app.lineView(1);
T.check(списокПартий.includes('pickLot('), 'список партий сохраняет выбор сразу');
T.check(!/\.lot=this\.value/.test(списокПартий), 'черновик напрямую больше не правится');
app.toggleLot(1);

T.head('Выпуск списывает выбранную партию');
app.makeBatch(app.REC('r-test'), 3);
T.near(партии[0].q, 2000, 0.0001, 'первая партия не тронута, г');
T.near(партии[1].q, 1000 - 300, 0.0001, 'из второй списано 3 × 100 г');
T.near(app.stockOf(воск), 2700, 0.0001, 'на складе стало, г');

T.head('Запись в журнале');
const запись = S.log.find(e => e.t === 'make');
T.check(!!запись, 'выпуск записан в журнал');
T.check(запись.q === 3, 'количество в журнале: 3');
T.near(запись.cost, 450, 0.01, 'себестоимость партии зафиксирована, ₽ (3 × 150)');
T.check(запись.use && запись.use[0].q === 300, 'записано, сколько материала ушло — 300 г');

T.head('Хватит ли материалов');
// Приложение считает по всему складу (2700 г), а не по выбранной партии (700 г).
// Это его нынешнее поведение, а не случайность: подсказка «хватит на N штук»
// отвечает на вопрос «сколько материала вообще есть», а не «сколько в этой закупке».
// Если решим считать по выбранной партии — ждём здесь 7 и правим canMake().
const сколько = app.canMake(изделие);
T.check(сколько.n === 27, 'хватит на 27 шт — считается по всему складу, 2700 г (получилось ' + сколько.n + ')');

T.head('Когда партии кончились');
app.consume(воск, 2700);
T.near(app.stockOf(воск), 0, 0.0001, 'склад пуст');
T.check(app.canMake(изделие).n === 0, 'больше выпустить нельзя');

T.done('партии и списание');
